-- B-  Exercícios de SELECT (Ordenando e agrupando dados)

-- 1 
SELECT NOME_ALUNO, ID_CLASSE FROM TB_ALUNO
ORDER BY NOME_ALUNO

-- 2
SELECT NOME_ALUNO, ID_CLASSE
FROM TB_ALUNO
ORDER BY CAST(COD_ALUNO AS VARCHAR(5)) DESC;

-- 3 
SELECT A.NOME_ALUNO, D.NOME_DISCIPLINA
FROM TB_ALUNO A
INNER JOIN TB_ALUNO_DISCIPLINA AD ON AD.COD_ALUNO = A.COD_ALUNO
INNER JOIN TB_DISCIPLINA D ON D.ID_DISCIPLINA = AD.ID_DISCIPLINA
WHERE D.ID_DISCIPLINA IN ('MAT','POR')
GROUP BY A.NOME_ALUNO, D.NOME_DISCIPLINA
ORDER BY A.NOME_ALUNO, D.NOME_DISCIPLINA;

-- C-   Exercícios de SELECT (Junção de Tabelas)

-- 1
SELECT A.NOME_ALUNO
FROM TB_ALUNO A
INNER JOIN TB_ALUNO_DISCIPLINA AD ON AD.COD_ALUNO = A.COD_ALUNO
INNER JOIN TB_DISCIPLINA D ON D.ID_DISCIPLINA = AD.ID_DISCIPLINA
WHERE D.ID_DISCIPLINA IN ('MAT','POR')
ORDER BY A.NOME_ALUNO

-- 2
SELECT A.NOME_ALUNO, A.END_ALUNO, D.NOME_DISCIPLINA
FROM TB_ALUNO A
INNER JOIN TB_ALUNO_DISCIPLINA AD ON AD.COD_ALUNO = A.COD_ALUNO
INNER JOIN TB_DISCIPLINA D ON D.ID_DISCIPLINA = AD.ID_DISCIPLINA
WHERE D.ID_DISCIPLINA IN ('FIS')
GROUP BY A.NOME_ALUNO, A.END_ALUNO, D.NOME_DISCIPLINA
ORDER BY A.NOME_ALUNO, D.NOME_DISCIPLINA;


-- 3 
SELECT A.NOME_ALUNO, D.NOME_DISCIPLINA, A.ID_CLASSE,
'ANDAR ' + CAST(C.ID_ANDAR AS VARCHAR(2)) AS ANDAR
FROM TB_ALUNO A
INNER JOIN TB_ALUNO_DISCIPLINA AD ON AD.COD_ALUNO = A.COD_ALUNO
INNER JOIN TB_DISCIPLINA D ON D.ID_DISCIPLINA = AD.ID_DISCIPLINA
INNER JOIN TB_CLASSE C ON C.ID_CLASSE = A.ID_CLASSE
WHERE D.ID_DISCIPLINA IN ('FIS')
GROUP BY A.NOME_ALUNO, D.NOME_DISCIPLINA, A.ID_CLASSE, C.ID_ANDAR 
ORDER BY A.NOME_ALUNO, D.NOME_DISCIPLINA;


-- D-  Exercícios de SELECT (OUTER JOIN)

-- 1

SELECT P.NOME_PROFESSOR, D.NOME_DISCIPLINA
FROM TB_PROFESSOR P
LEFT JOIN TB_DISCIPLINA D ON D.ID_PROFESSOR_DISCIPLINA = P.ID_PROFESSOR
ORDER BY NOME_PROFESSOR;


-- E-    Exercícios de SELECT (USE Clausula IN e/ou SUBSelect).

