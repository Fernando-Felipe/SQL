SELECT NOME_PROFESSOR
FROM TB_PROFESSOR
WHERE ID_PROFESSOR IN (
    SELECT ID_PROFESSOR_DISCIPLINA
    FROM TB_DISCIPLINA
    WHERE ID_DISCIPLINA IN (
        SELECT ID_DISCIPLINA
        FROM TB_ALUNO_DISCIPLINA
        WHERE COD_ALUNO IN (
            SELECT COD_ALUNO
            FROM TB_ALUNO
            WHERE SIGLA_ESTADO = 'PI'
              AND ID_CLASSE IN (
                  SELECT ID_CLASSE
                  FROM TB_CLASSE
                  WHERE ID_ANDAR = 3
              )
        )
    )
);

